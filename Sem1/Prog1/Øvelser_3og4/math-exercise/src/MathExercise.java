public class MathExercise {
    public static void main(String[] args) {
        System.out.println("Den største værdi af " + "10 og 20 er: " + Math.max(10, 20));
        System.out.println("2.45 afrundet til " + "nærmeste heltal er: " + Math.round(2.45));
        System.out.println("2.3 rundet op til " + "nærmeste heltal er: " + Math.ceil(2.3));
        System.out.println("Kvadratroden af 16 er: " + Math.sqrt(16));
        System.out.println("Arealet af en cirkel " + "med radius 5 er: " + Math.PI * Math.pow(5, 2));
    }
}
